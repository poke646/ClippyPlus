    public static IReadOnlyList<SupportedLanguage> SupportedLanguages { get; } =
    [
        new("en", T("Language.English", "en")),
        new("pl", T("Language.Polish", "pl")),
        new("es", T("Language.Spanish", "es")),
        new("de", T("Language.German", "de")),
        new("pt", T("Language.Portuguese", "pt")),
    ];

    public static string CurrentLanguageCode { get; private set; } = DefaultLanguageCode;

    public static void SetLanguage(string? languageCode)
    {
        CurrentLanguageCode = NormalizeLanguageCode(languageCode);
    }

    public static string NormalizeLanguageCode(string? languageCode)
    {
        if (string.IsNullOrWhiteSpace(languageCode))
        {
            return DefaultLanguageCode;
        }

        var normalized = languageCode.Trim().ToLowerInvariant();
        return Translations.ContainsKey(normalized) ? normalized : DefaultLanguageCode;
    }

    public static string T(string key)
    {
        return T(key, CurrentLanguageCode);
    }

    public static string T(string key, string languageCode)
    {
        var normalized = NormalizeLanguageCode(languageCode);
        if (Translations.TryGetValue(normalized, out var language) && language.TryGetValue(key, out var value))
        {
            return value;
        }

        return Translations[DefaultLanguageCode].TryGetValue(key, out var fallback) ? fallback : key;
    }

    public static string Format(string key, params object?[] args)
    {
        return string.Format(T(key), args);
    }
